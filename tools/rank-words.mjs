// Scores every word by how often it appears in spoken Swedish and writes data/ranks.js.
//
// Source: the FrequencyWords list built from OpenSubtitles (CC BY-SA 4.0),
// https://github.com/hermitdave/FrequencyWords — content/2018/sv/sv_50k.txt
//
// Usage: node tools/rank-words.mjs path/to/sv_50k.txt
//
// Nouns score the sum of their forms (bil, bilen, bilar, bilarna), verbs the sum of
// theirs (tala, talar, talade, talat), adjectives base + t + a forms. Particle verbs
// (tycka om) score a quarter of their verb. Other multi-word items score as their
// rarest word, scaled down per extra word.

import { readFileSync, writeFileSync } from 'node:fs';
import { WORDS } from '../data/words.js';
import { svForm } from '../js/svenska.js';

const file = process.argv[2];
if (!file) {
  console.error('Usage: node tools/rank-words.mjs path/to/sv_50k.txt');
  process.exit(1);
}

const lower = (s) => s.toLocaleLowerCase('sv');
const freq = new Map();
for (const line of readFileSync(file, 'utf8').replace(/^﻿/, '').split('\n')) {
  const [w, n] = line.trim().split(' ');
  // Case variants (Jag, JAG) are the same word, so add them up.
  if (w && n) freq.set(lower(w), (freq.get(lower(w)) || 0) + Number(n));
}
const count = (w) => freq.get(lower(w)) || 0;

const FORMS = {
  noun: (w) => (w.m || w.prop || w.fixed ? ['', 'def'] : ['', 'def', 'pl', 'pld']),
  verb: () => ['inf', 'pres', 'past', 'sup', 'imp'],
  adj: () => ['', 't', 'a'],
};
// Forms that are mostly other words: "var" (was / where), and little words.
const SKIP_FORMS = new Set(['var', 'för', 'om', 'så', 'som', 'den', 'det', 'en', 'ett']);

// Words that share their spelling with something more common.
const DAMPEN = {
  'animals:får': 0.02, 'basics:var': 0.3, 'basics:om': 0.5, 'time:vår': 0.2, 'shopping:kort': 0.5, 'work:fråga': 0.5,
  'animals:val': 0.1, 'clothes:rock': 0.3, 'clothes:ring': 0.3, 'animals:get': 0.1, 'animals:tiger': 0.3,
  'numbers:sex': 0.5, 'numbers:ett': 0.05, 'hobbies:lag': 0.3, 'people:man': 0.2, 'food:salt': 0.5,
};

const clean = (s) => s.replace(/[?!.,…]/g, ' ').trim();

function formsScore(word) {
  const make = FORMS[word.type];
  if (!make) return count(word.sv);
  const forms = new Set(make(word).map((f) => lower(svForm(word, f))).filter((f) => !SKIP_FORMS.has(f)));
  return [...forms].reduce((sum, f) => sum + count(f), 0);
}

function score(word) {
  const tokens = clean(word.sv).split(/\s+/).filter(Boolean);
  if (tokens.length === 1) return formsScore({ ...word, sv: tokens[0] });
  // Particle verbs and verbs with an object (tycka om, laga mat) score as their verb, scaled down.
  if (word.type === 'verb') return formsScore({ ...word, sv: tokens[0] }) / 4;
  // Each word of a phrase is far more common than the whole phrase, so scale down per extra word.
  return Math.min(...tokens.map(count)) / 4 ** (tokens.length - 1);
}

const ranks = {};
for (const w of WORDS) ranks[w.id] = Math.round(score(w) * (DAMPEN[w.id] || 1));

const body = Object.entries(ranks)
  .map(([id, n]) => `  ${JSON.stringify(id)}: ${n},`)
  .join('\n');
writeFileSync(
  new URL('../data/ranks.js', import.meta.url),
  `// Generated by tools/rank-words.mjs from the OpenSubtitles frequency list (CC BY-SA 4.0).\n` +
    `// Higher = more common in spoken Swedish.\nexport const RANKS = {\n${body}\n};\n`,
);

const top = Object.entries(ranks).sort((a, b) => b[1] - a[1]);
console.log('Top 40:', top.slice(0, 40).map(([id]) => id.split(':')[1]).join(', '));
console.log('Zero-scored:', top.filter(([, n]) => n === 0).map(([id]) => id).join(', ') || 'none');
